-- CHAT GROUPS SYSTEM - Auto-Sync Cron Job
-- =====================================================
-- This migration sets up a pg_cron job to automatically
-- synchronize group memberships every 15 minutes.
--
-- The job calls the auto-sync-groups Edge Function which:
-- - Evaluates membership criteria for all automatic groups
-- - Adds new members matching criteria
-- - Removes members no longer matching criteria
--
-- IMPORTANT: Removed members lose ALL access including history
-- =====================================================

-- Enable pg_cron extension if not already enabled
CREATE EXTENSION IF NOT EXISTS pg_cron;

-- Add comment for documentation
COMMENT ON EXTENSION pg_cron IS 'Cron-based job scheduler for PostgreSQL - used for auto-sync-groups job';

