import fs from "node:fs/promises";
import path from "node:path";

function argValue(name, fallback = null) {
  const equalsArg = process.argv.find((arg) => arg.startsWith(`--${name}=`));
  if (equalsArg) return equalsArg.slice(name.length + 3);

  const index = process.argv.indexOf(`--${name}`);
  if (index >= 0 && process.argv[index + 1]) return process.argv[index + 1];
  return fallback;
}

const PLAN_PATH = argValue("plan", "tmp/drive-organization/drive-organization-plan.json");
const OUT_PATH = argValue("out", "tmp/drive-organization/apply-drive-organization-plan.gs");
const ROOT_FOLDER_ID = argValue("root-folder-id", "1HcU2eCTb-jwar2yixG3f31PlWDbdvDuF");

function escapeJs(value) {
  return JSON.stringify(value);
}

function toPlanItem(item) {
  return {
    id: item.id,
    status: item.status,
    originalName: item.originalName,
    proposedName: item.proposedName,
    destinationFolder: item.destinationFolder,
    duplicateOf: item.duplicateOf || null,
  };
}

async function main() {
  const plan = JSON.parse(await fs.readFile(PLAN_PATH, "utf8"));
  const items = plan.items.map(toPlanItem);
  await fs.mkdir(path.dirname(OUT_PATH), { recursive: true });

  const source = `/**
 * Generated by scripts/catalog/generate-drive-apps-script.mjs.
 *
 * Purpose:
 * - Create the planned folder structure under the catalog root folder.
 * - Move files into their planned folders.
 * - Rename files to the proposed catalog-safe names.
 *
 * Safety:
 * - DRY_RUN is true by default. Run once to inspect the log.
 * - Set DRY_RUN = false only when the log looks correct.
 */
const ROOT_FOLDER_ID = ${escapeJs(ROOT_FOLDER_ID)};
const DRY_RUN = true;
const INCLUDE_REVIEW_ITEMS = true;
const PLAN = ${JSON.stringify(items, null, 2)};

function getOrCreateChildFolder(parent, name) {
  const folders = parent.getFoldersByName(name);
  if (folders.hasNext()) return folders.next();
  if (DRY_RUN) {
    Logger.log('[dry-run] create folder: ' + name);
    return null;
  }
  return parent.createFolder(name);
}

function getOrCreateFolderPath(root, folderPath) {
  let current = root;
  const parts = String(folderPath || '').split('/').filter(Boolean);
  for (let index = 0; index < parts.length; index++) {
    const part = parts[index];
    if (DRY_RUN) {
      Logger.log('[dry-run] ensure folder: ' + parts.slice(0, index + 1).join('/'));
      continue;
    }
    current = getOrCreateChildFolder(current, part);
  }
  return current;
}

function shouldApply(item) {
  if (item.status === 'ready_to_organize') return true;
  if (INCLUDE_REVIEW_ITEMS && item.status === 'needs_review') return true;
  if (item.status === 'duplicate_candidate') return true;
  return false;
}

function applyDriveOrganizationPlan() {
  const root = DriveApp.getFolderById(ROOT_FOLDER_ID);
  const summary = {
    total: PLAN.length,
    applied: 0,
    skipped: 0,
    errors: 0,
  };

  for (const item of PLAN) {
    if (!shouldApply(item)) {
      Logger.log('[skip] ' + item.originalName + ' status=' + item.status);
      summary.skipped++;
      continue;
    }

    try {
      const targetFolder = getOrCreateFolderPath(root, item.destinationFolder);
      const file = DriveApp.getFileById(item.id);
      Logger.log((DRY_RUN ? '[dry-run] ' : '') + item.originalName + ' -> ' + item.destinationFolder + '/' + item.proposedName);

      if (!DRY_RUN) {
        file.setName(item.proposedName);
        file.moveTo(targetFolder);
      }
      summary.applied++;
    } catch (error) {
      summary.errors++;
      Logger.log('[error] ' + item.id + ' ' + item.originalName + ': ' + error.message);
    }
  }

  Logger.log(JSON.stringify(summary));
}
`;

  await fs.writeFile(OUT_PATH, source);
  console.log(JSON.stringify({ outPath: OUT_PATH, rootFolderId: ROOT_FOLDER_ID, items: items.length }, null, 2));
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
